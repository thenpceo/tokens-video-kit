#!/usr/bin/env node
/**
 * Fetch the top trending tokenized stocks from the Tokens API, filter out
 * non-equity categories, sort by 24h volume, take the top 4, download their
 * logos, and bake everything into `data.js` so the composition can render
 * deterministically (no network at render time).
 *
 *   TOKENS_API_KEY=tok_xxx node fetch-trending.mjs [count]
 *
 * Docs: https://docs.tokens.xyz/v1  ·  GET https://api.tokens.xyz/v1/assets/trending
 * Keep your API key server-side — do not commit it.
 */
import { writeFileSync, mkdirSync } from "node:fs";

const KEY = process.env.TOKENS_API_KEY;
if (!KEY) { console.error("Set TOKENS_API_KEY (e.g. TOKENS_API_KEY=tok_... node fetch-trending.mjs)"); process.exit(1); }
const COUNT = Number(process.argv[2] || 4);
const BASE = "https://api.tokens.xyz/v1";

const fmtUSD = (v) => {
  if (v == null || isNaN(v)) return "—";
  const a = Math.abs(v);
  if (a >= 1e9) return "$" + (v / 1e9).toFixed(1) + "B";
  if (a >= 1e6) return "$" + (v / 1e6).toFixed(1) + "M";
  if (a >= 1e3) return "$" + (v / 1e3).toFixed(1) + "K";
  return "$" + v.toFixed(0);
};
const fmtPrice = (p) => {
  if (p == null || isNaN(p)) return "—";
  if (p >= 1000) return "$" + p.toLocaleString("en-US", { maximumFractionDigits: 0 });
  if (p >= 1) return "$" + p.toFixed(2);
  if (p >= 0.01) return "$" + p.toFixed(4);
  return "$" + p.toPrecision(2);
};
const fmtPct = (c) => (c == null || isNaN(c) ? "—" : (c >= 0 ? "+" : "") + c.toFixed(2) + "%");
const DISPLAY_NAME_OVERRIDES = {
  MU: "Micron",
};
const STOCK_CATEGORY = "equity";

const res = await fetch(`${BASE}/assets/trending`, { headers: { "x-api-key": KEY } });
if (!res.ok) { console.error("API error", res.status, await res.text()); process.exit(1); }
const { trending = [] } = await res.json();

const top = trending
  .filter((a) => a.category === STOCK_CATEGORY && a.market && a.market.volume24hUSD != null)
  .sort((a, b) => b.market.volume24hUSD - a.market.volume24hUSD)
  .slice(0, COUNT);

if (top.length < COUNT) {
  console.error(`Only found ${top.length} tokenized stocks with 24h volume; need ${COUNT}.`);
  process.exit(1);
}

mkdirSync(new URL("./assets/", import.meta.url), { recursive: true });
const out = [];
for (let i = 0; i < top.length; i++) {
  const a = top[i], m = a.market;
  let logo = "";
  try {
    const img = await fetch(a.imageUrl);
    if (img.ok) {
      const buf = Buffer.from(await img.arrayBuffer());
      const contentType = img.headers.get("content-type") || "";
      const textStart = buf.subarray(0, 120).toString("utf8").trimStart();
      const ext = contentType.includes("svg") || textStart.startsWith("<svg") || textStart.startsWith("<!--")
        ? "svg"
        : contentType.includes("webp")
          ? "webp"
          : contentType.includes("jpeg") || contentType.includes("jpg")
            ? "jpg"
            : "png";
      const file = `assets/logo${i + 1}.${ext}`;
      writeFileSync(new URL("./" + file, import.meta.url), buf);
      logo = file;
    }
  } catch (e) { console.warn("logo dl failed for", a.symbol, e.message); }
  // tidy long names → short label (drop parentheticals, "- Backed Securities", "Wrapped")
  const clean = (a.name || "")
    .replace(/\s*\(.*?\)\s*/g, " ")
    .replace(/\s*-\s*.*$/, "")
    .replace(/\bwrapped\s*/ig, "")
    .replace(/\s+/g, " ").trim();
  out.push({
    rank: i + 1,
    symbol: a.symbol,
    name: DISPLAY_NAME_OVERRIDES[a.symbol] || clean || a.symbol,
    logo,
    priceText: fmtPrice(m.price),
    volText: fmtUSD(m.volume24hUSD),
    changeText: fmtPct(m.priceChange24hPercent),
    up: (m.priceChange24hPercent ?? 0) >= 0,
  });
}

// today's date, e.g. "June 17th, 2026"
const now = new Date();
const ord = (d) => d + (([11,12,13].includes(d % 100)) ? "th" : ["th","st","nd","rd"][d % 10] || "th");
const MONTHS = ["January","February","March","April","May","June","July","August","September","October","November","December"];
const dateText = `${MONTHS[now.getMonth()]} ${ord(now.getDate())}, ${now.getFullYear()}`;

writeFileSync(
  new URL("./data.js", import.meta.url),
  "// generated by fetch-trending.mjs — top tokenized stocks by 24h volume\n" +
    `window.TRENDING_DATE = ${JSON.stringify(dateText)};\n` +
    `window.TRENDING_YEAR = ${JSON.stringify(String(now.getFullYear()))};\n` +
    "window.TRENDING = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log(`wrote data.js with ${out.length} assets:`);
out.forEach((a) => console.log(`  #${a.rank} ${a.symbol.padEnd(8)} vol ${a.volText.padStart(8)}  ${a.changeText}  ${a.priceText}`));
